def verify_asset(rel_path):
    full = os.path.join(public_dir, rel_path.lstrip("/"))
    if not os.path.exists(full):
        raise FileNotFoundError(f"Asset missing: {full} ({rel_path})")
    size = os.path.getsize(full)
    if size < 1000:
        raise ValueError(f"Asset too small: {full} ({size} bytes)")
    return rel_path


export const CANONICAL_RMC_SLUG = "rmc-plant-direct" as const;

export const RMC_SLUG_ALIASES: readonly string[] = [
  "rmc",
  "rmc-direct",
  "rmc-plant-direct",
  "ready-mix-concrete",
  "rmc-ready-mix-concrete",
  "rmc (ready mix concrete)",
  "rmc plant direct",
];

export function isRmcSlug(value?: string | null): boolean {
  if (!value) return false;
  const clean = value.trim().toLowerCase();
  if (!clean) return false;
  if (RMC_SLUG_ALIASES.includes(clean)) return true;
  return clean === "rmc-ready-mix-concrete" || clean.includes("ready-mix-concrete") || clean.startsWith("rmc-");
}

export function canonicalizeCategorySlug(value?: string | null): string {
  const raw = String(value || "").trim();
  if (!raw) return "";
  const lower = raw.toLowerCase();
  if (isRmcSlug(lower)) return CANONICAL_RMC_SLUG;
  if (lower.includes("solar")) return "solar-rooftop-power";
  if (lower.includes("lighting") || lower === "ceiling-panel-lights") return "lighting";
  if (lower.includes("wire") || lower === "electrical" || lower === "wires-mcb-electrical") return "wires-mcb-electrical";
  if (lower.includes("cctv")) return "cctv-networking";
  if (lower === "tools" || lower === "power-tools-safety" || lower === "tools-hardware") return "tools-hardware";
  if (lower === "cement" || lower === "steel" || lower === "tmt-steel") return "cement-civil-works";
  if (lower === "paint" || lower === "painting") return "paints-putty-primer";
  if (lower === "plumbing" || lower === "cpvc" || lower === "cpvc-pipes-hardware") return "cpvc-plumbing-tanks";
  return lower;
}


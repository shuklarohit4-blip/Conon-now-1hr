function computePackOf10(unitPrice: number, extraOffPct: number): { packOf10Price: number; packOf10DiscountPct: number } {
  const rawTen = unitPrice * 10;
  return {
    packOf10Price: Math.round((rawTen * (100 - extraOffPct)) / 100),
    packOf10DiscountPct: extraOffPct,
  };
}

function makeLightSku(
  base: Omit<LightingProduct, "discountPct" | "packOf10Price" | "packOf10DiscountPct" | "materialTag" | "categorySlug"> & {
    packExtraOff?: number;
  },
): LightingProduct {
  const discountPct = base.mrp > base.price ? Math.round(((base.mrp - base.price) / base.mrp) * 100) : 0;
  const pack = computePackOf10(base.price, base.packExtraOff ?? 10);
  return {
    ...base,
    discountPct,
    ...pack,
    materialTag: "Lighting",
    categorySlug: "lighting",
  };
}


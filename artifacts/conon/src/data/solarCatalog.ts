function makeSolarSku(
  base: Omit<SolarProduct, "discountPct" | "materialTag" | "categorySlug">,
): SolarProduct {
  const discountPct = base.mrp > base.price ? Math.round(((base.mrp - base.price) / base.mrp) * 100) : 0;
  return {
    ...base,
    discountPct,
    materialTag: "Solar & Rooftop Power",
    categorySlug: "solar-rooftop-power",
  };
}


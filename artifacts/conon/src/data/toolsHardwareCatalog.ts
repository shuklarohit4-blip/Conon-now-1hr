function makeToolSku(
  base: Omit<ToolHardwareProduct, "discountPct" | "categorySlug" | "materialTag">,
): ToolHardwareProduct {
  const discountPct = base.mrp > base.price ? Math.round(((base.mrp - base.price) / base.mrp) * 100) : 0;
  return {
    ...base,
    discountPct,
    categorySlug: "tools-hardware",
    materialTag: "Power Tools",
  };
}


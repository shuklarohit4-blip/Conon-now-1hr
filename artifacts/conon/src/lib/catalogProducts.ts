function resolveImage(name: string, fallback: string): string {
  if (manifest[name]) return manifest[name];
  if (manifest[name.trim()]) return manifest[name.trim()];
  // Search partial
  const key = Object.keys(manifest).find((k) => k.toLowerCase().includes(name.toLowerCase()));
  if (key && manifest[key]) return manifest[key];
  return fallback;
}


import { TEN_STAGE_ESCROW_SCHEDULE, BRAND_MATRIX_ROWS, type TurnkeyTierSpec } from "@/data/lucknowTurnkeyPackages";

export interface TurnkeyEstimatePdfParams {
  plotSqFt: number;
  floors: number;
  totalBuiltUpSqFt: number;
  zoneLabel: string;
  tier: TurnkeyTierSpec;
  effectiveRate: number;
  addons: { name: string; cost: number }[];
  grandTotal: number;
}

export async function downloadTurnkeyEstimatePdf(params: TurnkeyEstimatePdfParams): Promise<void> {
  const { jsPDF } = await import("jspdf");
  const doc = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4" });

  // Header
  doc.setFillColor(15, 23, 42);
  doc.rect(0, 0, 210, 34, "F");
  doc.setTextColor(251, 191, 36);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(15);
  doc.text("CONON INFRABUILT LIMITED", 14, 14);
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(10);
  doc.text("Lucknow Turnkey Construction Proposal & Home-Loan Estimate", 14, 21);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(8.5);
  doc.text("HQ: Skyline Plaza 3, Sushant Golf City, Lucknow | 150+ Projects Delivered | 7+ Yrs Civil Expertise", 14, 28);

  // Project Summary
  let y = 44;
  doc.setTextColor(15, 23, 42);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.text("1. Project & Package Summary", 14, y);
  y += 6;

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9.5);
  const summaryLines = [
    `Lucknow Zone: ${params.zoneLabel}`,
    `Plot Area: ${params.plotSqFt.toLocaleString("en-IN")} sq.ft  |  Floors: G+${Math.max(0, params.floors - 1)}  |  Built-Up Area: ${params.totalBuiltUpSqFt.toLocaleString("en-IN")} sq.ft`,
    `Selected Package: ${params.tier.name} (${params.tier.tagline}) @ Rs. ${params.effectiveRate.toLocaleString("en-IN")} / sq.ft`,
    `Warranty: ${params.tier.warrantyLabel}`,
  ];
  for (const line of summaryLines) {
    doc.text(line, 14, y);
    y += 5.5;
  }

  if (params.addons.length > 0) {
    doc.text(
      `Add-Ons: ${params.addons.map((a) => `${a.name} (Rs. ${a.cost.toLocaleString("en-IN")})`).join(", ")}`,
      14,
      y
    );
    y += 6;
  }

  // Total Cost Box
  doc.setFillColor(241, 245, 249);
  doc.rect(14, y, 182, 12, "F");
  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.text(`Estimated Turnkey Project Value: Rs. ${Math.round(params.grandTotal).toLocaleString("en-IN")}`, 18, y + 8);
  y += 18;

  // Brand Specs
  doc.setFontSize(10.5);
  doc.text(`2. Branded Material Specifications (${params.tier.name})`, 14, y);
  y += 5.5;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(8.5);
  for (const row of BRAND_MATRIX_ROWS) {
    const spec = row[params.tier.id];
    doc.text(`${row.category}: ${spec}`, 14, y);
    y += 4.5;
  }

  y += 4;
  doc.setFont("helvetica", "bold");
  doc.setFontSize(10.5);
  doc.text("3. 10-Stage CONON Escrow Payment Schedule", 14, y);
  y += 5.5;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(8.5);
  for (const st of TEN_STAGE_ESCROW_SCHEDULE) {
    const amt = Math.round((params.grandTotal * st.pct) / 100);
    doc.text(`Stage ${st.stage}: ${st.title} (${st.pct}%) — Rs. ${amt.toLocaleString("en-IN")}`, 14, y);
    y += 4.5;
  }

  y += 6;
  doc.setFontSize(8);
  doc.setTextColor(100, 116, 139);
  doc.text("Generated by CONON-NOW Build Studio | 100% Escrow Stage-Lock & 450-Point Civil Audit", 14, y);

  doc.save(`CONON-Turnkey-Proposal-${params.tier.id}-${params.totalBuiltUpSqFt}sqft.pdf`);
}
